"""Preview for pages that live as hand-written Webflow Embeds (porodice/, firme/).

    python3 tools/build_embed_preview.py porodice "Nutribox za porodice"

Concatenates <page>/embed-NN.html, in order, into <page>/index.html: the same markup
Webflow puts on the page, without Webflow's own CSS. Edit the embed files, not index.html.
"""
import sys
from pathlib import Path

repo = Path(__file__).resolve().parent.parent


def main(page, title):
    d = repo / page
    embeds = sorted(d.glob('embed-*.html'))
    if not embeds:
        raise SystemExit(f'no embed-*.html in {d}')
    body = '\n'.join(f'<!-- {e.name} -->\n<div class="w-embed">\n{e.read_text()}\n</div>' for e in embeds)
    (d / 'index.html').write_text(
        '<!doctype html>\n<html lang="sr">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f'<title>{title} (preview)</title>\n<meta name="robots" content="noindex">\n</head>\n'
        f'<body style="margin:0;background:#fff">\n<!-- Generated by tools/build_embed_preview.py from {", ".join(e.name for e in embeds)}. -->\n'
        f'{body}\n</body>\n</html>\n')
    print(f'{page}/index.html from {len(embeds)} embeds')


if __name__ == '__main__':
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1], sys.argv[2])
